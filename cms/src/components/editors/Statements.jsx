/**
 * The Rules editor — a Token's statements, one sentence per row.
 *
 * ## What this replaced
 * `EffectBlocks.jsx`: 1,080 lines in which five unrelated mechanics — target,
 * capability provision, trigger, upkeep and a *list* of modifiers — shared one
 * container, all five visible on every block whether or not they applied. About
 * 490 of those lines were that crowding, and another 190 were four separate
 * hand-rolled item pickers.
 *
 * Here a row shows only what its keyword needs, and there is one item picker.
 *
 * ## The row IS the sentence
 * Every row ends with its own rules text, generated by the same function the
 * game's tooltip uses. That is the validation: if the sentence says something
 * you did not mean, the rule says something you did not mean. A flipped sign
 * reads "5% **more** work time"; a tag typo reads "adjacent **Coste** Tokens".
 *
 * ## ⚠️ Requires is a view of `acceptedTokens`, not a statement
 * Owner decision Q5. That field gates whether a station produces anything at
 * all — `RecipeResolver.checkAcceptedTokens` is the highest-consequence reader
 * in the system — so it stays exactly where it is and only its presentation
 * moves into this list. The author sees one unified set of sentences; the
 * engine sees no change whatsoever.
 */

