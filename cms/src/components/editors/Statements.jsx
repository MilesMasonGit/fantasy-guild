/**
 * Which Tokens satisfy a requirement — the one thing the retired Requires form
 * showed that its sentence does not say.
 */
function RequiresNote({ requirement, tokens }) {
  const effects = useEntityStore((s) => s.effects);
  // Expanded: an `Acts as` rule lives in the library, so an unexpanded Token
  // provides nothing and this list would always read "nothing supplies this".
  const providers = Object.values(tokens).filter((t) =>
    providedTagsOf(expandBearer(t, effects || {}))
      .some((p) => p.tag === requirement.tag && (p.tier || 1) >= (requirement.minTier || 1))
  );
  return (
    <p className="text-[10px] text-gray-500" data-satisfied-by>
      Satisfied by:{' '}
      {providers.length === 0 ? (
        <span className="text-amber-400">nothing yet — this Token can never work</span>
      ) : (
        providers.map((t) => t.name).join(', ')
      )}
    </p>
  );
}
/**
 * One real statement, edited as a **sentence** (G-18).
 *
 * ⚠️ **The nested pickers are gone.** This row used to stack a payload box, a
 * role picker, a reach picker, a filter picker and a trigger clause, each in its
 * own labelled section — the "many nested dropdown menus" the owner asked to be
 * rid of. Every one of them was an expression of the same thing: the slots of a
 * statement. `statementSlots.js` describes those slots once, and `RulesLine`
 * renders the rule as the sentence it is, with its decision words clickable.
 *
 * ⚠️ **Retired in the same commit rather than left beside it.** Two editors for
 * one thing is the duplication this project keeps deleting, and a form that can
 * drift from the sentence is the exact drift UE-8 exists to prevent.
 *
 * What survives beneath it: a conversion's item table (E-8), and the cost strip
 * (E-6, P5) — the charge cost and the upkeep, which the sentence never says —
 * with the upkeep's items as a small table under that.
 */
function StatementRow({ statement, items, names, ctx, cursor, actions, canCreate, lockKeyword, note, onChange, onRemove, onMove, canMoveUp, canMoveDown }) {
  const keyword = getKeyword(statement.keyword);
  const upkeep = keyword?.upkeep ? statement.upkeep : null;

  return (
    <RowShell
      keywordId={statement.keyword}
      onRemove={onRemove}
      onMove={onMove}
      canMoveUp={canMoveUp}
      canMoveDown={canMoveDown}
    >
      <RulesLine
        statement={statement}
        onChange={onChange}
        names={names}
        ctx={ctx}
        cursor={cursor}
        actions={actions}
        lockKeyword={lockKeyword}
        form={<PayloadFields statement={statement} items={items} canCreate={canCreate} onChange={onChange} />}
        upkeepTable={upkeep && (
          <ItemList
            label="Consumes from the Bank"
            entries={upkeep.items || []}
            items={items}
            canCreate={canCreate}
            onChange={(next) => onChange({ upkeep: { ...upkeep, items: next } })}
          />
        )}
      />
      {note}
    </RowShell>
  );
}

/**
 * ⭐ **The one form that survives the Rules Line** (E-8, P4).
 *
 * A conversion's two item lists are a genuine table — several rows, each with
 * its own quantity — and a five-item exchange written out inline stops being
 * a sentence.
 *
 * ⚠️ **Eight forms were deleted here, not hidden**: Provides (effect, combine,
 * amount, direction, skill), Grants, Works as, Acts as, Restocks, Cannot,
 * Applies and Deals. Every decision they held is a slot in the line now, and
 * `FormFreeSlots.test.js` walks that inventory field by field — because a
 * decision only a form could reach becomes silently unauthorable the day the
 * form goes, and the last code review had already found one.
 */
function PayloadFields({ statement, items, canCreate, onChange }) {
  if (statement.keyword !== KEYWORD.CONVERTS) return null;
  const payload = statement.payload || {};
  const setPayload = (changes) => onChange({ payload: { ...payload, ...changes } });
  return (
    <div className="grid grid-cols-2 gap-3">
      <ItemList
        label="Spends from the Bank"
        entries={payload.consumes || []}
        items={items}
        canCreate={canCreate}
        onChange={(consumes) => setPayload({ consumes })}
      />
      <ItemList
        label="Produces on the board"
        entries={payload.produces || []}
        items={items}
        canCreate={canCreate}
        onChange={(produces) => setPayload({ produces })}
      />
    </div>
  );
}

/**
 * **The** item picker.
 *
 * There were four hand-rolled copies of this in the old editor, each with the
 * same `toLowerCase().includes()` filter written out again, and the create-item
 * modal wired up twice. One control, used everywhere.
 */
function ItemPicker({ label, value, items, onPick, className, canCreate = true }) {
  const [query, setQuery] = useState('');
  const [modalOpen, setModalOpen] = useState(false);

  const matches = query.trim()
    ? Object.values(items).filter((i) => (i.name || '').toLowerCase().includes(query.trim().toLowerCase())).slice(0, 5)
    : [];
  const exactExists = Object.values(items).some(
    (i) => (i.name || '').toLowerCase() === query.trim().toLowerCase()
  );

  return (
    <Field label={label} className={className}>
      {value ? (
        <div className="flex items-center gap-1.5">
          <span className="flex-1 truncate text-[11px] text-gray-300">{items[value]?.name || value}</span>
          <button
            onClick={() => onPick('')}
            className="text-gray-600 hover:text-red-400"
            style={{ background: 'none', border: 'none', cursor: 'pointer', padding: 0, lineHeight: 0 }}
          >
            <X size={11} />
          </button>
        </div>
      ) : (
        <div className="relative">
          <Search size={11} className="absolute left-2 top-1/2 -translate-y-1/2 text-gray-600" />
          <input
            type="text"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            placeholder="Search items…"
            className="w-full pl-6"
            style={{ fontSize: 11 }}
          />
        </div>
      )}

      {!value && query.trim() && (
        <div className="mt-1 space-y-1">
          {matches.map((i) => (
            <button
              key={i.id}
              onClick={() => { onPick(i.id); setQuery(''); }}
              className="w-full text-left px-2 py-1 rounded text-[11px] text-gray-300 hover:bg-white/5"
              style={{ background: 'transparent', border: 'none', cursor: 'pointer' }}
            >
              {i.name}
            </button>
          ))}
          {canCreate && !exactExists && (
            <button
              onClick={() => setModalOpen(true)}
              className="w-full flex items-center gap-1 px-2 py-1 rounded text-[11px] font-bold"
              style={{ background: 'var(--color-accent-muted)', color: 'var(--color-accent-hover)', border: 'none', cursor: 'pointer' }}
            >
              <Plus size={11} /> Create “{query.trim()}”
            </button>
          )}
        </div>
      )}

      <InlineItemModal
        isOpen={modalOpen}
        initialName={query.trim()}
        onClose={() => setModalOpen(false)}
        onCreated={(id) => { onPick(id); setQuery(''); }}
      />
    </Field>
  );
}

/** A list of `{itemId, quantity}` entries — upkeep, and both sides of Converts. */
function ItemList({ label, entries, items, onChange, canCreate = true }) {
  return (
    <div>
      {label && (
        <label className="text-[10px] font-bold uppercase tracking-wider block mb-1.5 text-gray-500">{label}</label>
      )}
      <div className="space-y-1.5">
        {entries.map((entry, i) => (
          <div key={i} className="flex items-center gap-1.5">
            <span className="flex-1 text-[11px] text-gray-300 truncate">
              {items[entry.itemId]?.name || entry.itemId}
            </span>
            <input
              type="number" min={1} value={entry.quantity ?? 1}
              onChange={(e) => onChange(entries.map((x, idx) => (idx === i ? { ...x, quantity: Math.max(1, Number(e.target.value)) } : x)))}
              className="w-16" style={{ fontSize: 11, padding: '3px 6px' }}
            />
            <button
              onClick={() => onChange(entries.filter((_, idx) => idx !== i))}
              className="text-gray-600 hover:text-red-400"
              style={{ background: 'none', border: 'none', cursor: 'pointer', padding: 0, lineHeight: 0 }}
            >
              <X size={11} />
            </button>
          </div>
        ))}
      </div>
      <ItemPicker
        label=""
        value=""
        items={items}
        canCreate={canCreate}
        onPick={(itemId) => itemId && onChange([...entries, { itemId, quantity: 1 }])}
      />
    </div>
  );
}

/**
 * Every capability tag the content actually uses — provided, or required.
 *
 * ⚠️ **Reads through the library** (Unified Effects P1). An `Acts as` rule lives
 * in a named entry now, not on the Token, so walking Tokens alone would return
 * an empty vocabulary and quietly turn every capability suggestion off.
 */
function useCapabilityVocabulary(tokens) {
  const effects = useEntityStore((s) => s.effects);
  return useMemo(() => {
    const tags = new Set();
    for (const t of Object.values(tokens)) {
      for (const p of providedTagsOf(expandBearer(t, effects || {}))) if (p.tag) tags.add(p.tag);
      for (const r of t.acceptedTokens || []) if (r?.tag) tags.add(r.tag);
    }
    return [...tags].sort();
  }, [tokens, effects]);
}

/**
 * A Token's provided capabilities, read the way the game reads them.
 *
 * ⚠️ The old editor typed its own list — `['pickaxe','axe','hammer','anvil',
 * 'saw','furnace','pie_tin','cookbook']` — straight into the component. That is
 * exactly the hand-maintained CMS vocabulary CMS-5 exists to forbid, and it had
 * already drifted from the content.
 */
function providedTagsOf(token) {
  const out = [];
  const defaultTier = token?.tier || 1;
  for (const s of statementsOf(token)) {
    if (s?.keyword === KEYWORD.ACTS_AS && s.payload?.tag) {
      out.push({ tag: s.payload.tag, tier: s.payload.tier || defaultTier });
    }
  }
  for (const p of token?.provides || []) {
    if (typeof p === 'string') out.push({ tag: p, tier: defaultTier });
    else if (p?.tag) out.push({ tag: p.tag, tier: p.tier || defaultTier });
  }
  return out;
}
