// Writes src/config/registries/legacySpriteNames.js (old sprite name -> new sprite name) from rename-list.json.
// Usage: node tools/asset-rename/generate-legacy-names.mjs [--check]   (--check: exit 1 if the module is out of date)
//
// An old name is a moved file's old name (keyFrom) or a manifest alias of it. An alias listed on two
// rows (the retired class names: fighter, wizard...) is left out: the resolver answers those from
// its own class table. A file's old name that another row lists as an alias drew that other file
// (the resolver answered it first), so it maps to that row's new name. An old name two kept files
// shared (ani_wolf) is left out too.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const OUT = path.join(ROOT, 'src/config/registries/legacySpriteNames.js');
const rows = JSON.parse(fs.readFileSync(path.join(HERE, 'rename-list.json'), 'utf8'));

export function legacyNames(list) {
    const live = list.filter(r => r.action !== 'delete' && r.keyTo);
    const aliasRows = new Map();
    for (const r of live) for (const a of r.aliases || []) {
        if (!aliasRows.has(a)) aliasRows.set(a, new Set());
        aliasRows.get(a).add(r.keyTo);
    }
    const table = new Map();
    for (const [alias, targets] of aliasRows) {
        if (targets.size === 1) table.set(alias, [...targets][0]);
    }
    const fromCount = new Map();
    for (const r of live) if (r.keyFrom) fromCount.set(r.keyFrom, (fromCount.get(r.keyFrom) || 0) + 1);
    for (const r of live) {
        if (!r.keyFrom || r.keyFrom === r.keyTo || aliasRows.has(r.keyFrom)) continue;
        // Two live files that shared one old name (a processing copy beside the real sheet): no answer.
        if (fromCount.get(r.keyFrom) > 1) continue;
        table.set(r.keyFrom, r.keyTo);
    }
    const newNames = new Set(live.map(r => r.keyTo));
    for (const [from, to] of table) {
        if (from === to) table.delete(from);
        else if (newNames.has(from)) throw new Error(`old name ${from} is also a new name; it cannot be mapped`);
    }
    return new Map([...table].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

function render(table) {
    const lines = [...table].map(([from, to]) => `    ${JSON.stringify(from)}: ${JSON.stringify(to)},`);
    return [
        '// GENERATED by tools/asset-rename/generate-legacy-names.mjs from tools/asset-rename/rename-list.json. Do not edit.',
        '',
        '/**',
        ' * Sprite names from before the art was renamed (docs/reference/ASSET_NAMING.md), each with the',
        ' * name of the same picture now. `resolveSpritePath` reads it, so content and saves that still hold',
        ' * an old name keep drawing; the CMS "apply renames" action and the save migration rewrite them.',
        ' */',
        'export const LEGACY_SPRITE_NAMES = Object.freeze({',
        ...lines,
        '});',
        ''
    ].join('\n');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
    const text = render(legacyNames(rows));
    if (process.argv.includes('--check')) {
        const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
        if (current !== text) {
            console.log(`${path.relative(ROOT, OUT)} is out of date: run node tools/asset-rename/generate-legacy-names.mjs`);
            process.exit(1);
        }
        console.log('legacySpriteNames.js is up to date');
    } else {
        fs.writeFileSync(OUT, text);
        console.log(`wrote ${path.relative(ROOT, OUT)}: ${legacyNames(rows).size} old names`);
    }
}
